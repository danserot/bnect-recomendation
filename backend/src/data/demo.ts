function seededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state += 0x6d2b79f5;
    let value = Math.imul(state ^ (state >>> 15), 1 | state);
    value ^= value + Math.imul(value ^ (value >>> 7), 61 | value);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

/** Stable IDs allow repeated seeding to upsert the same rows. No current-clock dependency. */
export function generateDemoTenders(seed = DEMO_SEED, count = 96): Tender[] {
  if (!Number.isInteger(count) || count < 0 || count > 10_000)
    throw new RangeError('Количество demo-тендеров должно быть от 0 до 10000.');
  const random = seededRandom(seed);
  const baseTime = Date.parse(DEMO_NOW);
  const day = 86_400_000;
  const commonRegions = ['astana', 'almaty', 'karaganda', 'astana'];
  return Array.from({ length: count }, (_, index) => {
    const category = categories[Math.floor(index / 8) % categories.length]!;
    const variant = index % 8;
    const externalNumber = `DEMO-${String(index + 1).padStart(4, '0')}`;
    const hash = createHash('sha256').update(`bnect-demo:${seed}:${externalNumber}`).digest('hex');
    const isClosed = index % 7 === 0;
    const unknownAvailability = index % 11 === 0;
    const regionId =
      index % 19 === 0
        ? null
        : variant < 4
          ? commonRegions[variant]!
          : regions[Math.floor(random() * regions.length)]!.id;
    const createdAt = new Date(baseTime - (4 + Math.floor(random() * 34)) * day).toISOString();
    return {
      id: `${hash.slice(0, 8)}-${hash.slice(8, 12)}-4${hash.slice(13, 16)}-8${hash.slice(17, 20)}-${hash.slice(20, 32)}`,
      externalNumber,
      title: category.titles[variant]!,
      regionId,
      createdAt,
      industryGroup: category.group,
      activity: category.activity,
      procurementMethod:
        index % 3 === 0
          ? 'Открытый конкурс'
          : index % 3 === 1
            ? 'Запрос ценовых предложений'
            : 'Тендер',
      procurementType: category.type,
      description: category.description,
      ...(unknownAvailability
        ? {}
        : {
            status: isClosed ? ('closed' as const) : ('open' as const),
            applicationDeadline: new Date(
              baseTime + (isClosed ? -(1 + (index % 3)) : 2 + (index % 17)) * day,
            ).toISOString(),
          }),
      source: 'demo' as const,
    };
  });
}

